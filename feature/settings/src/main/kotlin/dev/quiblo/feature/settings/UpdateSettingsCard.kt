/**
 * Whether the app asks about a newer release when it opens (`029` #7).
 *
 * **App-wide, on the App tab, and it is the one switch in this app that turns a network request
 * on rather than off by default.** Quiblo is installed from an APK and has no store behind it to
 * push a fix, so a build that never says it is out of date is a build somebody keeps for a year
 * without knowing there is a newer one. What it costs is one request to this project's own
 * releases page per launch, and the summary says so plainly rather than burying it — the same
 * standard the channel-logo switch is held to.
 *
 * Off means no request is made at all, not that the answer is hidden. Checking by hand stays
 * where it was.
 */
@Composable
internal fun UpdateSettingsCard(
    isEnabled: Boolean,
    onToggle: (Boolean) -> Unit,
) {
    Card(
        modifier = Modifier.fillMaxWidth(),
        colors = CardDefaults.cardColors(containerColor = MaterialTheme.colorScheme.surfaceVariant),
    ) {
        Column(modifier = Modifier.padding(16.dp)) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                verticalAlignment = Alignment.CenterVertically,
            ) {
                Column(modifier = Modifier.weight(1f)) {
                    Text(
                        text = stringResource(R.string.settings_updates_title),
                        style = MaterialTheme.typography.titleMedium,
                        fontWeight = FontWeight.SemiBold,
                    )
                    Text(
                        text = stringResource(R.string.settings_updates_summary),
                        style = MaterialTheme.typography.bodySmall,
                        color = MaterialTheme.colorScheme.onSurfaceVariant,
                        modifier = Modifier.padding(top = 4.dp),
                    )
                }
                Switch(checked = isEnabled, onCheckedChange = onToggle)
            }
        }
    }
}
