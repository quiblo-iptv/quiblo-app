package dev.quiblo.designsystem

import androidx.compose.foundation.Canvas
import androidx.compose.foundation.layout.size
import androidx.compose.runtime.Composable
import androidx.compose.runtime.remember
import androidx.compose.ui.Modifier
import androidx.compose.ui.geometry.CornerRadius
import androidx.compose.ui.geometry.Offset
import androidx.compose.ui.geometry.Rect
import androidx.compose.ui.geometry.RoundRect
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.Path
import androidx.compose.ui.graphics.drawscope.Stroke
import androidx.compose.ui.graphics.drawscope.withTransform
import androidx.compose.ui.semantics.contentDescription
import androidx.compose.ui.semantics.semantics
import androidx.compose.ui.unit.Dp

/**
 * The name, drawn: lowercase "quiblo" on the mark's own grid.
 *
 * **Drawn rather than typeset, because no font has these letters.** Every bowl is a small screen
 * with the mark's corner ratio, so the q, the b and the o repeat the mark three times, and the
 * stems end flat like the screen's edge. This is option A of the brand proposal, and its outlines
 * are the proposal's own. The TV banner draws the same strokes, generated by
 * `tools/brand_vectors.py`; change both.
 *
 * @param height the whole word, from the top of the b and l to the bottom of the q's descender. The
 *   x-height is about half of it, so 26dp sits beside a 20sp label the way the proposal's bar does.
 */
@Composable
fun QuibloWordmark(
    height: Dp,
    modifier: Modifier = Modifier,
    colour: Color = QuibloColours.Paper,
) {
    val geometry = remember { WordmarkGeometry() }
    Canvas(
        modifier = modifier
            .size(width = height * (WordmarkGeometry.WIDTH / WordmarkGeometry.HEIGHT), height = height)
            .semantics { contentDescription = QUIBLO_WORDMARK },
    ) {
        val unit = size.height / WordmarkGeometry.HEIGHT
        withTransform({ scale(unit, unit, pivot = Offset.Zero) }) {
            drawPath(geometry.strokes, colour, style = Stroke(width = WordmarkGeometry.STROKE))
            drawPath(geometry.dot, colour)
        }
    }
}

/**
 * The letters on their own grid: 297 units wide, 103 tall, the baseline at 78.
 *
 * One path for all the strokes rather than one per letter, so a translucent colour is laid down
 * once and the q's stem does not show darker where it crosses the bowl.
 */
private class WordmarkGeometry {

    val strokes: Path = Path().apply {
        // q: a screen, and a stem through its right edge down to the descender.
        addBowl(left = Q_BOWL)
        addStem(x = Q_STEM, top = X_HEIGHT, bottom = HEIGHT)

        // u: the bottom half of a screen, and a stem closing its right side.
        moveTo(U_LEFT, X_HEIGHT)
        lineTo(U_LEFT, BOWL_BOTTOM - CORNER)
        arcTo(corner(U_LEFT + CORNER), HALF_TURN, -QUARTER_TURN, false)
        lineTo(U_RIGHT - CORNER, BOWL_BOTTOM)
        arcTo(corner(U_RIGHT - CORNER), QUARTER_TURN, -QUARTER_TURN, false)
        lineTo(U_RIGHT, X_HEIGHT)
        addStem(x = U_RIGHT, top = X_HEIGHT, bottom = BASELINE)

        // i, its dot being the one filled shape in the word.
        addStem(x = I_STEM, top = X_HEIGHT, bottom = BASELINE)

        // b: a tall stem, and a screen with its left edge on it.
        addStem(x = B_STEM, top = 0f, bottom = BASELINE)
        addBowl(left = B_STEM)

        addStem(x = L_STEM, top = 0f, bottom = BASELINE)
        addBowl(left = O_BOWL)
    }

    val dot: Path = Path().apply {
        addRoundRect(
            RoundRect(
                rect = Rect(I_STEM - STROKE / 2f, 0f, I_STEM + STROKE / 2f, STROKE),
                cornerRadius = CornerRadius(DOT_CORNER),
            ),
        )
    }

    private fun Path.addBowl(left: Float) = addRoundRect(
        RoundRect(
            rect = Rect(left, BOWL_TOP, left + BOWL_WIDTH, BOWL_BOTTOM),
            cornerRadius = CornerRadius(CORNER),
        ),
    )

    private fun Path.addStem(x: Float, top: Float, bottom: Float) {
        moveTo(x, top)
        lineTo(x, bottom)
    }

    private fun corner(centreX: Float) = Rect(
        centreX - CORNER,
        BOWL_BOTTOM - CORNER * 2f,
        centreX + CORNER,
        BOWL_BOTTOM,
    )

    companion object {
        const val WIDTH = 297f
        const val HEIGHT = 103f
        const val STROKE = 12.5f

        private const val BASELINE = 78f
        private const val X_HEIGHT = 24f

        // Every bowl's centre line: 45.5 wide, 41.5 tall, corners of radius 15.
        private const val BOWL_TOP = 30.25f
        private const val BOWL_BOTTOM = 71.75f
        private const val BOWL_WIDTH = 45.5f
        private const val CORNER = 15f
        private const val DOT_CORNER = 3f

        // Where each letter stands, along the word.
        private const val Q_BOWL = 6.25f
        private const val Q_STEM = 51.75f
        private const val U_LEFT = 72.25f
        private const val U_RIGHT = 117.75f
        private const val I_STEM = 138.25f
        private const val B_STEM = 158.75f
        private const val L_STEM = 224.75f
        private const val O_BOWL = 245.25f

        private const val QUARTER_TURN = 90f
        private const val HALF_TURN = 180f
    }
}
