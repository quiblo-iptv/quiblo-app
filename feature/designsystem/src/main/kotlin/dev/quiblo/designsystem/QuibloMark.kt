/**
 * The Quiblo mark, filling the space it is given: a screen whose corner turns into the tail of a Q.
 *
 * **What it replaced read as a magnifying glass over a play button**, which is the stock icon for
 * "search videos". This keeps the letter and drops the clip art: the body is a television's
 * rounded rectangle — no magnifier has corners — and the tail is short and sits mostly inside it,
 * so it cannot be read as a handle. The empty screen is where the viewer's film goes, and the
 * splash uses it that way: it flies through it into the catalogue.
 *
 * Drawn to the edges of its box, so `size(120.dp)` is a mark 120dp across. The same geometry is
 * in the launcher icons and the TV banner, generated by `tools/brand_vectors.py`; change both.
 *
 * @param lit draws the warm light inside the screen, as the launcher icon does.
 */
@Composable
fun QuibloMark(
    modifier: Modifier = Modifier,
    colour: Color = Color.White,
    lit: Boolean = false,
) {
    val geometry = remember { MarkGeometry() }
    Canvas(
        // Offscreen, because the cut beside the tail is drawn by clearing what is under it.
        modifier = modifier.graphicsLayer { compositingStrategy = CompositingStrategy.Offscreen },
    ) {
        val unit = size.minDimension / MarkGeometry.GRID
        translate(left = (size.width - size.minDimension) / 2f, top = (size.height - size.minDimension) / 2f) {
            withTransform({ scale(unit, unit, pivot = Offset.Zero) }) {
                with(geometry) {
                    if (lit) drawLight(alpha = colour.alpha)
                    drawStrokes(colour)
                }
            }
        }
    }
}

/**
 * The mark's shapes on its own 100-unit grid, and how to draw them part-way — which the splash
 * needs, because it draws the ring on and grows the tail in.
 *
 * Kept as paths rather than recomputed per frame: the splash draws this sixty times a second.
 */
internal class MarkGeometry {

    /** The ring's centre line, starting at the tail and running clockwise, so it draws on from there. */
    val ring: Path = Path().apply {
        val start = cornerPoint(CORNER_HIGH, CORNER_HIGH, TAIL_ANGLE)
        moveTo(start.x, start.y)
        arcTo(corner(CORNER_HIGH, CORNER_HIGH), TAIL_ANGLE, EIGHTH_TURN, false)
        lineTo(CORNER_LOW, EDGE_HIGH)
        arcTo(corner(CORNER_LOW, CORNER_HIGH), QUARTER_TURN, QUARTER_TURN, false)
        lineTo(EDGE_LOW, CORNER_LOW)
        arcTo(corner(CORNER_LOW, CORNER_LOW), HALF_TURN, QUARTER_TURN, false)
        lineTo(CORNER_HIGH, EDGE_LOW)
        arcTo(corner(CORNER_HIGH, CORNER_LOW), THREE_QUARTER_TURN, QUARTER_TURN, false)
        lineTo(EDGE_HIGH, CORNER_HIGH)
        arcTo(corner(CORNER_HIGH, CORNER_HIGH), 0f, EIGHTH_TURN, false)
        close()
    }

    /** The screen inside the ring: where the light is, and the hole the splash flies through. */
    val counter: Path = Path().apply {
        addRoundRect(
            RoundRect(
                rect = Rect(COUNTER_LOW, COUNTER_LOW, COUNTER_HIGH, COUNTER_HIGH),
                cornerRadius = CornerRadius(COUNTER_RADIUS),
            ),
        )
    }

    private val measure = PathMeasure().apply { setPath(ring, false) }
    private val partial = Path()

    /**
     * The ring, the cut either side of the tail, and the tail — [ring] and [tail] of the way drawn.
     *
     * Must be drawn into an offscreen layer: the cut clears what is beneath it.
     */
    fun DrawScope.drawStrokes(colour: Color, ring: Float = 1f, tail: Float = 1f) {
        if (ring >= 1f) {
            drawPath(this@MarkGeometry.ring, colour, style = Stroke(width = STROKE))
        } else if (ring > 0f) {
            partial.reset()
            measure.getSegment(0f, measure.length * ring, partial, true)
            drawPath(partial, colour, style = Stroke(width = STROKE, cap = StrokeCap.Round))
        }
        // Always cleared, even before the tail grows: it also hides where the ring starts.
        drawLine(
            color = Color.Black,
            start = Offset(CUT_FROM, CUT_FROM),
            end = Offset(CUT_TO, CUT_TO),
            strokeWidth = CUT_WIDTH,
            cap = StrokeCap.Round,
            blendMode = BlendMode.Clear,
        )
        if (tail > 0f) {
            val end = TAIL_FROM + (TAIL_TO - TAIL_FROM) * tail.coerceAtMost(1f)
            drawLine(
                color = colour,
                start = Offset(TAIL_FROM, TAIL_FROM),
                end = Offset(end, end),
                strokeWidth = STROKE,
                cap = StrokeCap.Round,
            )
        }
    }

    /** The warm light inside the screen, at [alpha]. */
    fun DrawScope.drawLight(alpha: Float) {
        if (alpha <= 0f) return
        clipPath(counter) {
            drawRect(
                brush = LIGHT,
                topLeft = Offset(COUNTER_LOW, COUNTER_LOW),
                size = Size(COUNTER_HIGH - COUNTER_LOW, COUNTER_HIGH - COUNTER_LOW),
                alpha = alpha.coerceAtMost(1f),
            )
        }
    }

    companion object {
        /** The grid the mark is designed on. */
        const val GRID = 100f

        /** The centre of the screen, which is where the splash's camera aims. */
        const val CENTRE = 50f

        const val STROKE = 13f

        // The centre line: a 72-unit screen, 14..86, with corners of radius 26.
        private const val EDGE_LOW = 14f
        private const val EDGE_HIGH = 86f
        private const val RADIUS = 26f
        private const val CORNER_LOW = EDGE_LOW + RADIUS
        private const val CORNER_HIGH = EDGE_HIGH - RADIUS

        // The screen inside: the centre line less half the stroke.
        private const val COUNTER_LOW = EDGE_LOW + STROKE / 2f
        private const val COUNTER_HIGH = EDGE_HIGH - STROKE / 2f
        private const val COUNTER_RADIUS = RADIUS - STROKE / 2f

        // The tail at 45 degrees, mostly inside the screen, and the cut a little longer either way.
        private const val TAIL_FROM = 62f
        private const val TAIL_TO = 87f
        private const val CUT_FROM = 61f
        private const val CUT_TO = 89f
        private const val CUT_WIDTH = STROKE + 2 * 4f

        private const val TAIL_ANGLE = 45f
        private const val EIGHTH_TURN = 45f
        private const val QUARTER_TURN = 90f
        private const val HALF_TURN = 180f
        private const val THREE_QUARTER_TURN = 270f
        private const val DEGREES_TO_RADIANS = (Math.PI / 180.0).toFloat()

        /** Hot at the middle, tungsten, then ember at the edge, gone at the stroke. */
        private val LIGHT = Brush.radialGradient(
            0f to QuibloColours.GlowCore,
            0.45f to QuibloColours.Glow,
            0.8f to QuibloColours.Ember.copy(alpha = 0.55f),
            1f to QuibloColours.Ember.copy(alpha = 0f),
            center = Offset(CENTRE, 54f),
            radius = 33f,
        )

        private fun corner(cx: Float, cy: Float) = Rect(cx - RADIUS, cy - RADIUS, cx + RADIUS, cy + RADIUS)

        private fun cornerPoint(cx: Float, cy: Float, degrees: Float) = Offset(
            cx + RADIUS * cos(degrees * DEGREES_TO_RADIANS),
            cy + RADIUS * sin(degrees * DEGREES_TO_RADIANS),
        )
    }
}
